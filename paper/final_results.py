"""Generate FINAL_RESULTS.md - the single source of truth for every number.

The paper must not take numbers from terminal output, from a README, or from memory.
Every value in every figure, table, caption and sentence is read from the JSON the
experiment wrote, and this file is the only place a number may be looked up.

Two validation checks are reported separately because they answer different
questions over different sets, and conflating them invites exactly the question the
reviewer would ask:

* **solvability** - over the 24 *benchmark scenarios*, does a successful action
  sequence exist?
* **terrain check** - over the 15 *terrain-kit primitives* (which include
  primitives that are not benchmark scenarios), are the geometry self-consistent and
  is the terrain walkable?

    python paper/final_results.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "tasks" / "task3_reobservability" / "generated"
OUT = ROOT / "paper" / "FINAL_RESULTS.md"

BUDGETS = (1, 3, 5, 10)
#: Bench display order, from the lower bound upward, privileged last.
MAIN_ORDER = ["Random", "Reactive", "HistoryOnly", "NBV", "Oracle", "OracleSearch"]


def load(name):
    path = GEN / name
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def f3(x):
    return "n/a" if x is None else f"{float(x):.3f}"


def f2(x):
    return "n/a" if x is None else f"{float(x):.2f}"


def main() -> None:
    bench = load("benchmark_multistep_B_scored.json")
    rand = load("random_baseline.json")
    model = load("consequence_model.json")
    gap = load("geometry_gap.json")
    hist = load("history_necessity.json")
    mem = load("memory_sufficiency.json")
    odom = load("odometry_baselines.json")
    calib = load("safety_calibration.json")
    joint = load("joint_decision.json")
    dep = load("dependence_analysis.json")
    hz = load("horizon_planner.json")
    cross = load("cross_mechanism.json")
    solv = load("solvability.json")
    tcheck = load("terrain_check.json")

    random_scenes = set(rand.get("terrains", []))
    learned_scenes = set(model.get("planner", {}).get("per_terrain", {}))
    if random_scenes != learned_scenes:
        raise SystemExit("Audit guard: Random and learned artifacts cover different scene sets "
                         f"({len(random_scenes)} vs {len(learned_scenes)}). "
                         "Do not publish a pooled comparison. See paper/audit_20261004/AUDIT.md.")

    L = ["# FINAL RESULTS", "",
         "> **Single source of truth.** Generated by `paper/final_results.py` from the",
         "> JSON artefacts each experiment wrote. Do not hand-edit and **do not take a",
         "> number for the paper from anywhere else** - not from a README, not from",
         "> terminal output, not from memory.", ""]

    # -- main benchmark ----------------------------------------------------
    L += ["## Main benchmark (24 terrains, protocol B, budget 10 x 3.0 s)", ""]
    L += ["| Method | RSR@1 | RSR@3 | RSR@5 | RSR@10 | Cost (m) |",
          "| --- | ---: | ---: | ---: | ---: | ---: |"]
    summary = bench["summary"]
    for name in MAIN_ORDER:
        if name == "Random":
            m = rand["mean_over_seeds"]
            L.append(f"| Random (lower bound, 3 seeds) | {f3(m['rsr@1'])} | {f3(m['rsr@3'])} "
                     f"| {f3(m['rsr@5'])} | {f3(m['rsr@10'])} | {f2(rand['mean_cost_m'])} |")
            continue
        s = summary.get(name)
        if s:
            L.append(f"| {name} | {f3(s['rsr@1'])} | {f3(s['rsr@3'])} | {f3(s['rsr@5'])} "
                     f"| {f3(s['rsr@10'])} | {f2(s.get('mean_motion_cost_m'))} |")
    pl = model.get("planner", {})
    if pl:
        L.append(f"| **Consequence planner (ours)** | **{f3(pl['rsr@1'])}** "
                 f"| **{f3(pl['rsr@3'])}** | **{f3(pl['rsr@5'])}** | **{f3(pl['rsr@10'])}** "
                 f"| **{f2(pl['mean_motion_cost_m'])}** |")
    L += ["",
          "### The two comparisons the paper is allowed to make", "",
          f"1. **Against Random (the uninformed floor):** "
          f"{f3(rand['mean_over_seeds']['rsr@10'])} -> {f3(pl.get('rsr@10'))}, while "
          f"motion cost falls from {f2(rand['mean_cost_m'])} m to "
          f"{f2(pl.get('mean_motion_cost_m'))} m "
          f"({round((pl.get('mean_motion_cost_m', 0) / rand['mean_cost_m'] - 1) * 100)}%).",
          "   *Consequence planning beats uninformed stochastic exploration while "
          "using less motion.*",
          "",
          f"2. **Against the classical deterministic policies:** "
          f"{f3(summary['Reactive']['rsr@10'])} -> {f3(pl.get('rsr@10'))}.",
          "   *Action-conditioned consequence prediction substantially outperforms "
          "fixed and reactive strategies.*",
          "",
          "**Forbidden claim.** `0.250 -> 0.792` must **not** be presented as the "
          "headline improvement, because Random reaches "
          f"{f3(rand['mean_over_seeds']['rsr@10'])} and thus sits *above* every "
          "classical rule. The classical rules are deterministic commitment policies: "
          "they repeat the same failing action until the budget expires. That is why "
          "Random beats them, and it must be stated.", "",
          "### Wilson 95% intervals at RSR@10", ""]
    n = len(bench["terrains"])
    for name in MAIN_ORDER:
        s = summary.get(name)
        if s:
            L.append(f"- {name}: RSR@10 = {f3(s['rsr@10'])}")
    L.append(f"- 24 terrains; Random is a mean over {len(rand['seeds'])} seeds and its "
             f"interval is the spread across seeds, not a Wilson interval.")
    L.append("")

    # -- H1 / H2 / H3 ------------------------------------------------------
    hp = hist["pairs"]
    L += ["## H1 - observation ambiguity (8 paired worlds)", "",
          f"- pixel-identical observations: "
          f"**{sum(1 for p in hp if p['verdict']['observations_equivalent'])}/{len(hp)}**",
          f"- opposite optimal action: "
          f"**{sum(1 for p in hp if p['verdict']['optimal_actions_differ'])}/{len(hp)}**",
          f"- no history-independent action: "
          f"**{sum(1 for p in hp if not p['verdict']['history_independent_action_exists'])}/{len(hp)}**",
          f"- max absolute pixel difference: "
          f"**{max(p['observation_equality'].get('max_abs_pixel_diff', 0) for p in hp)}**",
          ""]
    a = mem["aggregate"]
    L += ["## H2 - memory insufficiency (6 paired worlds)", "",
          f"- observations identical: **{a['pairs_with_identical_observations']}/{a['n_pairs']}**",
          f"- memory identical: **{a['pairs_with_identical_memory']}/{a['n_pairs']}**",
          f"- optimal action differs: **{a['pairs_with_different_optimal_actions']}/{a['n_pairs']}**",
          f"- successful sets disjoint: **{a['pairs_with_no_common_successful_action']}/{a['n_pairs']}**",
          "",
          "> The disjointness line is the bound on the claim: the sets **overlap**, so "
          "H2 shows that memory does not determine the optimal action, not that no "
          "fixed rule can succeed.", ""]
    s = gap["summary"]
    c = s["confusion"]
    L += ["## H3 - geometry is not physical re-observability (240 (s,a) pairs)", "",
          f"- confusion: G0P0 {c['G0_P0']}, G0P1 {c['G0_P1']}, "
          f"G1P0 **{c['G1_P0']}**, G1P1 {c['G1_P1']}",
          f"- share of geometric positives that fail physically: "
          f"**{f3(s['gap_share_of_geometric_positives'])}**",
          f"- overall G=1 and P=0 rate: {f3(s['geometric_overconfidence_rate'])}",
          f"- geometry under-predicts (G=0, P=1): {f3(s['geometric_miss_rate'])}",
          f"- **oracle at the executed pose agrees with P: "
          f"{f3(s['G_actual_equals_P_rate'])}**",
          f"- pose error, gap rows {s['pose_error_gap_rows_m']} m vs agreeing rows "
          f"{s['pose_error_agree_rows_m']} m",
          f"- gap-row error breakdown: {s['pose_error_breakdown_gap']}",
          ""]

    # -- E-Odom ------------------------------------------------------------
    L += ["## E-Odom - is it just localization? (24 terrains x 3 modes x 3 drifts)", "",
          "| Drift | Mode | RSR@1 | RSR@3 | RSR@10 | Failures |",
          "| --- | --- | ---: | ---: | ---: | --- |"]
    for drift in ("perfect", "moderate", "realistic"):
        for mode, e in odom["results"][drift]["by_mode"].items():
            L.append(f"| {drift} | {mode} | {f3(e['rsr@1'])} | {f3(e['rsr@3'])} "
                     f"| {f3(e['rsr@10'])} | {e['failure_taxonomy']} |")
    L += ["",
          "> Perfect localisation does not solve the task, and the failures under "
          "perfect localisation are **physical terminations**, not positional ones. "
          "Perfect and moderate drift produce identical results, so this is not an "
          "odometry-accuracy problem.", ""]

    # -- E4-x --------------------------------------------------------------
    conds = {x["inputs"]: x for x in model["conditions"]}
    L += ["## E4-1 - information ablation (leave-one-terrain-out, 2240 samples)", "",
          "| Inputs | ROC-AUC | PR-AUC | Brier | ECE | Pose MAE |",
          "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for k in ("O", "M", "O+M", "O+M+a"):
        x = conds[k]
        L.append(f"| {k} | {f3(x['roc_auc'])} | {f3(x['pr_auc'])} | {f3(x['brier'])} "
                 f"| {f3(x['ece'])} | {f3(x['delta_mae_mean'])} |")
    L += ["",
          f"- O+M -> O+M+a : **{round(conds['O+M+a']['roc_auc'] - conds['O+M']['roc_auc'], 3):+}**",
          f"- M -> O+M : **{round(conds['O+M']['roc_auc'] - conds['M']['roc_auc'], 3):+}**",
          ""]
    L += ["## E4-2 - analytic vs learned pose consequence", "",
          "| Component | Analytic | Learned |", "| --- | ---: | ---: |"]
    for comp in ("forward_m", "lateral_m", "height_m", "yaw_rad"):
        L.append(f"| {comp} | {f3(model['analytic']['delta_mae'][comp])} "
                 f"| {f3(conds['O+M+a']['delta_mae'][comp])} |")
    L.append(f"| **mean** | **{f3(model['analytic']['delta_mae_mean'])}** "
             f"| **{f3(conds['O+M+a']['delta_mae_mean'])}** |")
    L += ["", "> The analytic model is better for **height**; the statement is that "
              "the learned model wins on the components that decide success, not that "
              "learning is better everywhere.", ""]

    hb = {x["history"]: x for x in model["history_ablation"]}
    L += ["## E4-4 - history ablation", "", "| H | AUC | Brier | Pose MAE |",
          "| --- | ---: | ---: | ---: |"]
    for k in sorted(hb):
        L.append(f"| H{k} | {f3(hb[k]['roc_auc'])} | {f3(hb[k]['brier'])} "
                 f"| {f3(hb[k]['delta_mae_mean'])} |")
    L += ["", "> Visibility AUC is flat; pose error improves and saturates at H4.", ""]

    L += ["## E4-3 - consequence prediction to task performance", ""]
    L.append(f"- consequence planner RSR@10 = {f3(pl.get('rsr@10'))}, RSR@1 = "
             f"{f3(pl.get('rsr@1'))}, cost {f2(pl.get('mean_motion_cost_m'))} m")
    L.append(f"- classical RSR@10 = {f3(summary['Reactive']['rsr@10'])}, cost "
             f"{f2(summary['Reactive']['mean_motion_cost_m'])} m")
    L.append(f"- Random RSR@10 = {f3(rand['mean_over_seeds']['rsr@10'])}, cost "
             f"{f2(rand['mean_cost_m'])} m")
    L.append("")

    # -- negatives ---------------------------------------------------------
    head = model.get("full_consequence", {}).get("safety_head", {})
    L += ["## E4-5 / E4c - the safety head", "",
          f"- termination head ROC-AUC {f3(head.get('roc_auc'))}, "
          f"PR-AUC {f3(head.get('pr_auc'))}, positive rate {head.get('positive_rate')}",
          f"- one-step success: Oracle-V "
          f"{f3(model['full_consequence']['Oracle-V']['success_rate'])} -> Oracle-S "
          f"{f3(model['full_consequence']['Oracle-S']['success_rate'])} "
          f"(the term has value with ground truth)",
          f"- learned: V-only {f3(model['full_consequence']['Learned-V']['success_rate'])}"
          f" -> hard veto "
          f"{f3(model['full_consequence']['Learned-V+S']['success_rate'])}",
          ""]
    d = calib["calibration_diagnostics"]
    L += ["| Variant | overall ECE | **decision-band ECE** |",
          "| --- | ---: | ---: |"]
    for k in ("raw", "temperature", "isotonic"):
        L.append(f"| {k} | {f3(d[k]['ece'])} | **{f3(d[k]['decision_boundary_ece'])}** |")
    L += ["", f"- best operating point per variant: "
              f"{ {k: v['best']['success_rate'] for k, v in calib['sweeps'].items()} }",
          f"- no-safety baseline: {f3(calib['no_safety']['success_rate'])}",
          "",
          "> Halving the decision-band ECE produces zero planning gain.", ""]

    L += ["## E4e / E4e-0 - joint consequence decision", "",
          f"- no-safety baseline {f3(joint['baseline_v_only']['success_rate'])}; "
          f"joint head {f3(joint['joint_head']['success_rate'])}; "
          f"product {f3(joint['product_pV_pS']['success_rate'])}",
          f"- odds ratio **{f3(dep['level_1_overall']['odds_ratio'])}** "
          f"CI {dep['level_1_overall']['odds_ratio_ci']}",
          f"- P(S|V) {f3(dep['level_1_overall']['P(S|V)'])} vs "
          f"P(S|not V) {f3(dep['level_1_overall']['P(S|not V)'])}",
          f"- actions per state: visible "
          f"{dep['action_sets']['mean_visible_actions']}, safe "
          f"{dep['action_sets']['mean_safe_actions']}",
          f"- **conflict states "
          f"{dep['action_sets']['states_with_conflict']}/"
          f"{dep['action_sets']['n_decision_states']} = "
          f"{f3(dep['action_sets']['states_with_conflict_rate'])}**",
          "",
          "> Visibility and safety are negatively coupled, but the coupling almost "
          "never creates a decision conflict, so the headroom for any joint decision "
          "is bounded below the noise of any learned head.", ""]

    r = hz["results"]
    L += ["## E4d - action horizon (receding horizon, learned rollout only)", "",
          "| H | RSR@1 | RSR@3 | RSR@5 | RSR@10 | Cost (m) |",
          "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for k in sorted(r):
        x = r[k]
        L.append(f"| {k} | {f3(x['rsr@1'])} | {f3(x['rsr@3'])} | {f3(x['rsr@5'])} "
                 f"| {f3(x['rsr@10'])} | {f2(x['mean_motion_cost_m'])} |")
    L += ["", "> No horizon is significantly better on any budget; each costs "
              "1.78-2.09x the motion; lookahead rescues two genuinely sequential "
              "terrains and breaks eight that one step solves.", ""]

    L += ["## E-OOD - cross-mechanism generalisation", "",
          f"- within-mechanism reference: pose MAE "
          f"{f3(cross['within_mechanism_summary']['mean_pose_mae'])}, AUC "
          f"{f3(cross['within_mechanism_summary']['mean_roc_auc'])}",
          f"- across mechanisms: pose MAE "
          f"{f3(cross['cross_mechanism_summary']['mean_pose_mae'])}, AUC "
          f"{f3(cross['cross_mechanism_summary']['mean_roc_auc'])}",
          f"- learned beats analytic on "
          f"**{cross['cross_mechanism_summary']['mechanisms_where_learned_beats_analytic']}"
          f"/{cross['cross_mechanism_summary']['n_mechanisms']}** held-out mechanisms",
          ""]
    for name, x in cross["by_mechanism"].items():
        L.append(f"- {name}: pose MAE {f3(x['pose_mae_learned'])} vs analytic "
                 f"{f3(x['analytic_pose_mae'])}, AUC {f3(x['roc_auc'])}")
    L += ["",
          "> **Confound that must be stated.** The `occlusion direction` fold reaches "
          "AUC 0.533, but that fold also removes 1680 of 2240 training rows, so the "
          "mechanism shift is confounded with a large reduction in data and cannot be "
          "attributed to mechanism transfer alone.", ""]

    # -- validation checks, kept separate ----------------------------------
    L += ["## Two validation checks - different sets, different questions", "",
          "These must never be conflated. They are reported over different "
          "collections and answer different questions, and mixing them invites the "
          "obvious question of why one number is short of the other.", "",
          "| Check | Set | Question | Result |",
          "| --- | --- | --- | --- |"]
    if solv:
        L.append(f"| Solvability | **{len(solv['solvable'])} benchmark scenarios** "
                 f"| does a successful action sequence exist? "
                 f"| **{len(solv['solvable'])}/{len(solv['solvable'])} solvable**, "
                 f"upper bound 1.00 |")
    if tcheck:
        L.append(f"| Terrain check | **{tcheck['n_terrains']} terrain-kit primitives** "
                 f"| is the geometry self-consistent and the terrain walkable? "
                 f"| **{tcheck['n_passed']}/{tcheck['n_terrains']} pass** "
                 f"({tcheck['n_locomotion_tested']} walked, "
                 f"{tcheck['n_geometry_consistent']} geometry-consistent) |")
    L += ["",
          "The terrain kit includes primitives that are **not** benchmark scenarios "
          "(`stairs_down`, `window_wall`, `flat`, `crater`, `undulating`). The single "
          "failure is the legacy `undulating` height-field terrain, which is excluded "
          "from the benchmark suite. So `14/15` concerns terrain primitives and "
          "`24/24` concerns task solvability; neither contradicts the other.", ""]

    OUT.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L[:34]))
    print(f"\n... wrote {OUT} ({len(L)} lines)")


if __name__ == "__main__":
    main()
